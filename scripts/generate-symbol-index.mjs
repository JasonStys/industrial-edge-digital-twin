/**
 * @file generate-symbol-index.mjs
 * @brief Generates exact line locations for source declarations referenced by file headers.
 * @details Main variables: repositoryRoot, sourceFiles, outputPath, and generated Markdown.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";
import { format as formatText } from "prettier";

const repositoryRoot = fileURLToPath(new URL("../", import.meta.url));
const outputPath = path.join(repositoryRoot, "docs", "generated", "symbol-index.md");
const includedExtensions = new Set([".cpp", ".hpp", ".js", ".mjs", ".ts"]);
const skippedDirectories = new Set(["build", "build-release", "dist", "node_modules", "reports"]);

/** Recursively find version-controlled source candidates in stable lexical order. */
async function discover(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const discovered = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (entry.name.startsWith(".") || skippedDirectories.has(entry.name)) continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) discovered.push(...(await discover(fullPath)));
    else if (includedExtensions.has(path.extname(entry.name))) discovered.push(fullPath);
  }
  return discovered;
}

/** Extract named declarations and significant module variables without parsing generated files. */
function symbolsFor(source) {
  const symbols = [];
  const patterns = [
    /\b(?:class|struct|enum(?:\s+class)?|interface|type)\s+([A-Za-z_][A-Za-z0-9_]*)/,
    /\b(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/,
    /\b(?:export\s+)?class\s+([A-Za-z_][A-Za-z0-9_]*)/,
    /\b(?:export\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::[^=]+)?=/,
    /\b(?:[A-Za-z_][A-Za-z0-9_:<>]*\s+)+([A-Za-z_][A-Za-z0-9_]*)\s*\([^;]*\)\s*(?:const\s*)?(?:noexcept\s*)?\{/,
  ];
  for (const [index, line] of source.split(/\r?\n/u).entries()) {
    for (const pattern of patterns) {
      const match = pattern.exec(line);
      if (match?.[1] !== undefined && !symbols.some((item) => item.name === match[1])) {
        symbols.push({ name: match[1], line: index + 1 });
        break;
      }
    }
  }
  return symbols;
}

const sourceFiles = await discover(repositoryRoot);
const sections = [];
for (const sourcePath of sourceFiles) {
  if (sourcePath === fileURLToPath(import.meta.url)) continue;
  const relative = path.relative(repositoryRoot, sourcePath).replaceAll("\\", "/");
  const source = await readFile(sourcePath, "utf8");
  const symbols = symbolsFor(source);
  const rows =
    symbols.length === 0
      ? "- No named declaration; see the file-level header at line 1."
      : symbols
          .map(({ name, line }) => `- \`${name}\` — [line ${line}](../../${relative}#L${line})`)
          .join("\n");
  sections.push(`### \`${relative}\`\n\n${rows}`);
}

const rawGenerated = `<!-- Generated by scripts/generate-symbol-index.mjs. Do not edit by hand. -->

# Source symbol index

This index supplies exact, reproducible line locations for the classes, functions, interfaces,
and important module variables summarized by each source file header. Regenerate it after source
changes with \`pnpm symbols\`; CI rejects stale output.

${sections.join("\n\n")}
`;
const generated = await formatText(rawGenerated, {
  parser: "markdown",
  printWidth: 100,
  proseWrap: "always",
});

if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== generated) {
    process.stderr.write("docs/generated/symbol-index.md is stale; run pnpm symbols\n");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated, "utf8");
  process.stdout.write(`Indexed ${sourceFiles.length - 1} source files.\n`);
}
